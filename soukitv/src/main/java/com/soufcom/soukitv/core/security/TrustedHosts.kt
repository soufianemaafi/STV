package com.soufcom.soukitv.core.security

private val MASKED_FALLBACK_HOSTS = listOf(
    byteArrayOf(0x7A, 0x72, 0x7D, 0x65, 0x79, 0x7B, 0x7B, 0x65, 0x7A, 0x7E, 0x7D, 0x65, 0x7A, 0x72, 0x7B),
    byteArrayOf(0x7A, 0x72, 0x7D, 0x65, 0x79, 0x7B, 0x7B, 0x65, 0x7A, 0x7E, 0x7D, 0x65, 0x7A, 0x73, 0x7F),
    byteArrayOf(0x7A, 0x72, 0x7D, 0x65, 0x79, 0x7B, 0x7B, 0x65, 0x7A, 0x7E, 0x7D, 0x65, 0x7A, 0x73, 0x7D)
)

/** Hôtes STV de confiance par défaut (obfusqués, XOR 0x4B), utilisés si `config.json` n'en fournit pas. */
fun defaultTrustedHosts(): Set<String> =
    MASKED_FALLBACK_HOSTS.map { SecretDecoder.decode(it).lowercase() }.toSet()
